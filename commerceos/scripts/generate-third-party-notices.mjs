import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const outputPath = join(projectRoot, 'THIRD_PARTY_NOTICES.md');
const checkOnly = process.argv.includes('--check');
const pnpm = process.platform === 'win32' ? 'pnpm.cmd' : 'pnpm';

const result = spawnSync(pnpm, ['licenses', 'list', '--json'], {
  cwd: projectRoot,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});

if (result.error || result.status !== 0) {
  process.stderr.write(result.stderr || String(result.error));
  process.exit(1);
}

const report = JSON.parse(result.stdout);
const packages = new Map();
const unreadablePaths = [];

for (const [reportedLicense, entries] of Object.entries(report)) {
  for (const entry of entries) {
    for (const packagePath of entry.paths ?? []) {
      try {
        const metadata = JSON.parse(
          readFileSync(join(packagePath, 'package.json'), 'utf8'),
        );
        const id = `${metadata.name ?? entry.name}@${metadata.version ?? entry.versions?.[0] ?? 'unknown'}`;
        if (packages.has(id)) continue;
        packages.set(id, {
          id,
          name: metadata.name ?? entry.name,
          version: metadata.version ?? entry.versions?.join(', ') ?? 'unknown',
          license: normalizeLicense(metadata.license) || reportedLicense,
          author: normalizeAuthor(metadata.author ?? entry.author),
          source: normalizeSource(metadata, entry.homepage),
          path: packagePath,
        });
      } catch (error) {
        unreadablePaths.push(`${packagePath}: ${error.message}`);
      }
    }
  }
}

const packageList = [...packages.values()].sort((left, right) =>
  left.id.localeCompare(right.id),
);
const textGroups = new Map();
const missingLicenseFiles = [];

for (const packageInfo of packageList) {
  const noticeFiles = findNoticeFiles(packageInfo.path);
  if (noticeFiles.length === 0) {
    missingLicenseFiles.push(packageInfo.id);
    continue;
  }

  for (const fileName of noticeFiles) {
    const content = readFileSync(join(packageInfo.path, fileName), 'utf8')
      .replaceAll('\r\n', '\n')
      .trim();
    if (!content) continue;
    const digest = createHash('sha256').update(content).digest('hex');
    const existing = textGroups.get(digest) ?? {
      content,
      files: new Set(),
      packages: new Set(),
    };
    existing.files.add(fileName);
    existing.packages.add(packageInfo.id);
    textGroups.set(digest, existing);
  }
}

const licenseCounts = new Map();
for (const packageInfo of packageList) {
  licenseCounts.set(
    packageInfo.license,
    (licenseCounts.get(packageInfo.license) ?? 0) + 1,
  );
}

const lines = [
  '# Third-party notices',
  '',
  '> Generated by `pnpm licenses:generate` from the exact installed dependency',
  '> graph. Do not edit this file manually.',
  '',
  'MDCart itself is licensed under the MIT License. The packages listed here',
  'remain under their respective upstream licenses. This inventory includes',
  'runtime and development packages because both are used to build and validate',
  'the distributed application.',
  '',
  `This snapshot contains **${packageList.length} unique package versions** and`,
  `**${textGroups.size} unique license or notice texts**. Optional native`,
  'packages vary by operating system, so release maintainers must regenerate',
  'this file on the platform that produces the release artifact.',
  '',
  'Geist Sans and Geist Mono are fetched and bundled by the application build.',
  'Their separate SIL Open Font License is preserved in',
  '[LICENSES/OFL-1.1-Geist.txt](./LICENSES/OFL-1.1-Geist.txt).',
  '',
  '## License summary',
  '',
  '| SPDX expression or reported license | Package versions |',
  '| --- | ---: |',
  ...[...licenseCounts.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([license, count]) => `| ${escapeCell(license)} | ${count} |`),
  '',
  '## Package inventory',
  '',
  '| Package | Version | License | Author or steward | Source |',
  '| --- | --- | --- | --- | --- |',
  ...packageList.map(
    (packageInfo) =>
      `| ${escapeCell(packageInfo.name)} | ${escapeCell(packageInfo.version)} | ${escapeCell(packageInfo.license)} | ${escapeCell(packageInfo.author)} | ${sourceLink(packageInfo.source)} |`,
  ),
  '',
  '## Upstream license and notice texts',
  '',
  'Identical texts are grouped once. The package list above remains the',
  'authoritative mapping of package versions to reported license expressions.',
  '',
];

const sortedTextGroups = [...textGroups.values()].sort((left, right) =>
  [...left.packages][0].localeCompare([...right.packages][0]),
);

sortedTextGroups.forEach((group, index) => {
  const packageIds = [...group.packages].sort();
  lines.push(
    `### Notice ${index + 1}`,
    '',
    `Packages: ${packageIds.map((id) => `\`${id}\``).join(', ')}`,
    '',
    `Source files: ${[...group.files]
      .sort()
      .map((file) => `\`${file}\``)
      .join(', ')}`,
    '',
    ...group.content.split('\n').map((line) => `    ${line}`),
    '',
  );
});

if (missingLicenseFiles.length > 0 || unreadablePaths.length > 0) {
  lines.push(
    '## Review warnings',
    '',
    'Package metadata identified the following licenses, but a standalone',
    'license or notice file could not be collected automatically. Review these',
    'packages before distributing a binary or container image.',
    '',
  );
  for (const id of missingLicenseFiles.sort()) lines.push(`- ${id}`);
  for (const warning of unreadablePaths.sort()) lines.push(`- ${warning}`);
  lines.push('');
}

const generated = `${lines.join('\n')}\n`;

if (checkOnly) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== generated) {
    process.stderr.write(
      'THIRD_PARTY_NOTICES.md is out of date. Run pnpm licenses:generate.\n',
    );
    process.exit(1);
  }
  process.stdout.write('THIRD_PARTY_NOTICES.md is current.\n');
} else {
  writeFileSync(outputPath, generated);
  process.stdout.write(
    `Wrote THIRD_PARTY_NOTICES.md for ${packageList.length} package versions.\n`,
  );
}

function findNoticeFiles(packagePath) {
  return readdirSync(packagePath)
    .filter((fileName) =>
      /^(licen[cs]e|copying|copyright|notice)(\..*)?$/i.test(fileName),
    )
    .filter((fileName) => {
      const filePath = join(packagePath, fileName);
      return statSync(filePath).isFile() && statSync(filePath).size <= 1024 * 1024;
    })
    .sort();
}

function normalizeLicense(license) {
  if (typeof license === 'string') return license;
  if (license && typeof license.type === 'string') return license.type;
  return '';
}

function normalizeAuthor(author) {
  if (typeof author === 'string') return author.replaceAll('\n', ' ').trim();
  if (!author || typeof author !== 'object') return '';
  return [author.name, author.email, author.url]
    .filter((value) => typeof value === 'string' && value.trim())
    .join(' · ');
}

function normalizeSource(metadata, fallbackHomepage) {
  const homepage = metadata.homepage ?? fallbackHomepage;
  if (typeof homepage === 'string' && /^https?:\/\//.test(homepage)) {
    return homepage;
  }
  const repository =
    typeof metadata.repository === 'string'
      ? metadata.repository
      : metadata.repository?.url;
  if (typeof repository !== 'string') return '';
  const normalized = repository
    .replace(/^git\+/, '')
    .replace(/^git:\/\/github\.com\//, 'https://github.com/')
    .replace(/\.git$/, '');
  return /^https?:\/\//.test(normalized) ? normalized : '';
}

function escapeCell(value) {
  return String(value ?? '')
    .replaceAll('|', '\\|')
    .replaceAll('\n', ' ')
    .trim();
}

function sourceLink(source) {
  return source ? `[link](${source})` : '';
}
